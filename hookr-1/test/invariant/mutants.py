"""The mutation catalog: hand-written one-edit mutants of the value-moving contracts, for test/invariant/mutate.py.

Each mutant names its contract, the file it edits, the exact source text it replaces (the anchor, which must occur
once in the file) and the text that replaces it, plus the suites that must catch it. A mutant breaks one thing: a
comparison flipped at its boundary, a rounding direction, a bound constant, an access check, a timelock off by one, a
split's arithmetic. Every mutant changes behaviour a suite can observe: none is an equivalent edit (an edit no input
can tell from the original), and a mutant that turns out to be one is removed with the proof beside it in the notes.

Suites are (profile, forge test arguments). The lane suites (test/lane) run only under the lane profile, which isolates
every top-level call; the rest run under the default profile.
"""

# Mutant ids: the contract's prefix and a number. Add a mutant at the end of its contract's block.


def D(*paths, extra=()):
    """A default-profile suite over test files or globs."""
    glob = paths[0] if len(paths) == 1 else "{" + ",".join(paths) + "}"
    return ("default", ["--match-path", glob, *extra])


def L(*paths, extra=()):
    """A lane-profile suite over test files or globs."""
    glob = paths[0] if len(paths) == 1 else "{" + ",".join(paths) + "}"
    return ("lane", ["--match-path", glob, *extra])


def M(id, contract, file, title, frm, to, *suites):
    return {"id": id, "contract": contract, "file": file, "title": title, "from": frm, "to": to, "suites": list(suites)}


